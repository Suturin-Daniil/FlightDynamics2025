WGS84_GravityConstant =  1.931852652458e-3; % WGS84_b*WGS84_GravityPole / (WGS84_GravityEquator * WGS84_a) - 1;

WGS84_w = 7.292115e-5; % Среднее значение угловой скорости вращения Земли

WGS84_GM = 3.986004418e14; % Геоцентрическая гравитационная константа - произведение массы Земли на гравитационную постоянную

