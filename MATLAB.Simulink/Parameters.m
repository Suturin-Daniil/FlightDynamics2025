WGS84_a = 6378137.0; % Большая полуось эллипсоида

WGS84_FlatteningFactor = 298.257223563; % Параметр сжатия эллипсоида
% равный обратной величине к полярному сжатию f = (a - b) / a

WGS84_b = (1 - 1/WGS84_FlatteningFactor)*WGS84_a; % малая полуось эллипса

WGS84_e1 = sqrt((WGS84_a*WGS84_a - WGS84_b*WGS84_b) / (WGS84_a*WGS84_a)); % Первый эксцентриситет

WGS84_e2 = sqrt((WGS84_a*WGS84_a - WGS84_b*WGS84_b) / (WGS84_b*WGS84_b)); % Второй эксцентриситет

